-- 메디큐브톡 커뮤니티 스키마
-- 매 기동마다 실행된다 (spring.sql.init.mode=always) → 모든 문장은 IF NOT EXISTS 로 멱등하게 작성한다.
-- 삭제는 소프트 삭제(deleted_at)만 사용하고 물리 삭제가 없으므로 FK 에 ON DELETE 를 두지 않는다.
-- 시각은 초 단위로 저장한다 (Integration spec C4).

CREATE TABLE IF NOT EXISTS posts (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(20)  NOT NULL,   -- 코드포인트 기준 20자 (PostgreSQL VARCHAR(n) 은 문자 단위)
    content     TEXT         NOT NULL,
    author      TEXT         NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    deleted_at  TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS comments (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id     BIGINT       NOT NULL,
    content     TEXT         NOT NULL,
    author      TEXT         NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    deleted_at  TIMESTAMPTZ,
    CONSTRAINT fk_comments_post FOREIGN KEY (post_id) REFERENCES posts (id)
);

-- 누가 어떤 글에 좋아요를 눌렀는지. 같은 사용자 · 같은 글은 한 행만 허용한다.
CREATE TABLE IF NOT EXISTS post_likes (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id     BIGINT  NOT NULL,
    user_id     TEXT    NOT NULL,
    CONSTRAINT fk_post_likes_post      FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT uk_post_likes_post_user UNIQUE (post_id, user_id)   -- 좋아요 토글 재시도 판별에 이 이름을 사용한다
);

-- 좋아요 수와 낙관적 락 버전. 게시글 행과 분리해 좋아요가 글 수정과 버전을 공유하지 않게 한다.
CREATE TABLE IF NOT EXISTS post_like_counts (
    post_id     BIGINT  PRIMARY KEY,
    like_count  INTEGER NOT NULL DEFAULT 0,
    version     BIGINT  NOT NULL DEFAULT 0,
    CONSTRAINT fk_post_like_counts_post      FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT ck_post_like_counts_non_negative CHECK (like_count >= 0)
);
